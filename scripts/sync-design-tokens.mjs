#!/usr/bin/env node
/**
 * Quezby "Arena" design language — authored in OKLCH, shipped as hex.
 *
 * React Native cannot parse `oklch()`, so this converts every value in
 * `apps/mobile/design/palette.mjs` to sRGB hex and writes
 * `apps/mobile/src/ui/tokens.ts`.
 *
 *   pnpm tokens
 *
 * `roles` becomes the one `Palette`, exported as `arena` — the game has one
 * look and does not follow the phone's light/dark setting. Every other export
 * becomes a fixed `as const` group of the same name. Only `marks` may hold hex,
 * which is copied untouched; anywhere else a hex value is an error.
 *
 * Run it in the same change that touches the palette; the output is generated
 * and must not be hand-edited.
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

import { oklchToHex } from './lib/oklch.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = join(root, 'apps/mobile/design/palette.mjs');
const OUT = join(root, 'apps/mobile/src/ui/tokens.ts');

/** The groups whose values are copied as authored hex. */
const HEX_GROUPS = new Set(['marks']);

/** The doc comment over each fixed group in the output. */
const NOTES = {
  reel: "The feed's own colours — content, not chrome.",
  marks:
    "Other companies' logo colours, copied exactly — never themed, never tuned.",
};

const HEX = /^#(?:[0-9a-f]{6}|[0-9a-f]{8})$/i;

function convert(value, { allowHex = false } = {}) {
  if (typeof value !== 'string') {
    throw new Error(`not a colour: ${JSON.stringify(value)}`);
  }
  if (HEX.test(value)) {
    if (allowHex) return value;
    throw new Error(`hex is only allowed in marks, author ${value} in oklch()`);
  }
  const match = value.match(
    /oklch\(\s*([\d.]+)\s+([\d.]+)\s+([\d.]+)(?:\s*\/\s*([\d.]+))?\s*\)/,
  );
  if (!match) throw new Error(`not an oklch value: ${value}`);
  return oklchToHex(
    Number(match[1]),
    Number(match[2]),
    Number(match[3]),
    match[4] ? Number(match[4]) : 1,
  );
}

const renderObject = (object, options, indent = '  ') =>
  Object.entries(object)
    .map(([key, value]) =>
      Array.isArray(value)
        ? `${indent}${key}: [${value.map((v) => `'${convert(v, options)}'`).join(', ')}],`
        : `${indent}${key}: '${convert(value, options)}',`,
    )
    .join('\n');

const { roles, ...groups } = await import(pathToFileURL(SOURCE).href);

if (!roles || typeof roles !== 'object' || 'light' in roles || 'dark' in roles) {
  throw new Error('palette.mjs must export one flat roles object — the arena has no light/dark pair');
}

const keys = Object.keys(roles);

const fixed = Object.entries(groups)
  .map(([name, values]) => {
    const note = NOTES[name] ?? 'Fixed colours.';
    const body = renderObject(values, { allowHex: HEX_GROUPS.has(name) });
    return `/** ${note} */\nexport const ${name} = {\n${body}\n} as const;\n`;
  })
  .join('\n');

writeFileSync(
  OUT,
  `/* GENERATED by scripts/sync-design-tokens.mjs — do not edit by hand.
 *
 * The Quezby "Arena" palette, converted from the OKLCH values authored in
 * apps/mobile/design/palette.mjs.
 */

export type Palette = {
${keys.map((key) => `  ${key}: string;`).join('\n')}
};

export const arena: Palette = {
${renderObject(roles)}
};

${fixed}`,
  'utf8',
);

console.log(`wrote ${OUT}`);
